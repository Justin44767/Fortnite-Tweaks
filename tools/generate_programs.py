"""Generate Iris entry points; all rendering code lives in shaders/program and lib."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEOMETRY = {
    'gbuffers_basic': ['BASIC'],
    'gbuffers_textured': [],
    'gbuffers_textured_lit': [],
    'gbuffers_terrain': ['TERRAIN'],
    'gbuffers_water': ['TERRAIN', 'TRANSLUCENT'],
    'gbuffers_block': ['ENTITY'],
    'gbuffers_entities': ['ENTITY'],
    'gbuffers_entities_translucent': ['ENTITY', 'TRANSLUCENT'],
    'gbuffers_hand': [],
    'gbuffers_hand_water': ['TRANSLUCENT'],
    'gbuffers_weather': ['WEATHER'],
    'gbuffers_spidereyes': ['EMISSIVE', 'OVERLAY'],
    'gbuffers_beaconbeam': ['EMISSIVE', 'OVERLAY'],
    'gbuffers_armor_glint': ['EMISSIVE', 'OVERLAY'],
}
POST = ['deferred', 'composite', 'composite1', 'composite2', 'composite3', 'final']

def programs():
    for folder, dimension in [('', 0), ('world0', 0), ('world-1', -1), ('world1', 1)]:
        for name in [*GEOMETRY, 'shadow', *POST]:
            defines = GEOMETRY.get(name, [])
            header = '#version 330 compatibility\n// Generated by tools/generate_programs.py.\n'
            header += f'#define NERO_DIMENSION {dimension}\n'
            header += ''.join(f'#define {d}\n' for d in defines)
            for ext in ['vsh', 'fsh']:
                source = 'geometry' if name in GEOMETRY else name
                if name in POST and ext == 'vsh':
                    source = 'fullscreen'
                yield Path(folder) / f'{name}.{ext}', header + f'#include "/program/{source}.{ext}"\n'

def generate():
    for relative, content in programs():
        path = ROOT / 'shaders' / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)

if __name__ == '__main__':
    generate()
